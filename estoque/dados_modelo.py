def linhas_da_secao(valor_padrao, texto):
    """Converte o texto de uma seção em tuplas (codigo, nome, valor)."""
    for linha in texto.strip().splitlines():
        partes = linha.strip().split("|")
        codigo, nome = partes[0], partes[1]
        valor = partes[2] if len(partes) > 2 else valor_padrao
        yield codigo, nome, valor
