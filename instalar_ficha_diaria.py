PASTA = Path.cwd()
APP = "ficha_diaria"


def sair(msg):
    print("ERRO:", msg)
    sys.exit(1)


def backup(caminho):
    destino = caminho.with_name(caminho.name + time.strftime(".%Y%m%d-%H%M%S.bak"))
    shutil.copy2(caminho, destino)
    print(f"   copia de seguranca: {destino.name}")


def instalar_arquivos():
    print("1) Arquivos do app", APP)
    for rel, b64 in ARQUIVOS.items():
        destino = PASTA / rel
        destino.parent.mkdir(parents=True, exist_ok=True)
        if destino.exists() and rel.endswith("migrations/__init__.py"):
            continue
        destino.write_bytes(base64.b64decode("".join(b64.split())))
        print("   ok", rel)


def ajustar_settings():
    print("2) config/settings.py")
    caminho = PASTA / "config" / "settings.py"
    texto = caminho.read_text(encoding="utf-8")
    if re.search(r"""['"]%s['"]""" % APP, texto):
        print("   ja tem o app em INSTALLED_APPS")
        return
    m = re.search(r"INSTALLED_APPS\s*=\s*\[", texto)
    if not m:
        sair(f"nao achei INSTALLED_APPS em config/settings.py; acrescente '{APP}' na mao.")
    fim = texto.index("]", m.end())
    aspas = "'" if "'django.contrib" in texto[m.end():fim] else '"'
    ultima = [l for l in texto[m.end():fim].splitlines() if l.strip()][-1]
    recuo = ultima[: len(ultima) - len(ultima.lstrip())] or "    "
    trecho = texto[m.end():fim].rstrip()
    if trecho and not trecho.endswith(","):
        trecho += ","
    novo = texto[:m.end()] + trecho + f"\n{recuo}{aspas}{APP}{aspas},\n" + texto[fim:]
    backup(caminho)
    caminho.write_text(novo, encoding="utf-8")
    print(f"   '{APP}' acrescentado em INSTALLED_APPS")


def ajustar_urls():
    print("3) config/urls.py")
    caminho = PASTA / "config" / "urls.py"
    texto = caminho.read_text(encoding="utf-8")
    if f"{APP}.urls" in texto:
        print("   a rota ficha/ ja existe")
        return
    if not re.search(r"from django.urls import[^\n]*\binclude\b", texto):
        sair("config/urls.py nao importa 'include'; use: from django.urls import include, path")
    aspas = "'" if "path('" in texto else '"'
    linha = f"path({aspas}ficha/{aspas}, include({aspas}{APP}.urls{aspas})),"
    linhas = texto.splitlines()
    alvo = next((i for i, l in enumerate(linhas) if "membros.urls" in l), None)
    if alvo is not None:
        recuo = linhas[alvo][: len(linhas[alvo]) - len(linhas[alvo].lstrip())]
        linhas.insert(alvo, recuo + linha)
    else:
        i = next((i for i, l in enumerate(linhas) if re.match(r"\s*urlpatterns\s*=\s*\[", l)), None)
        if i is None:
            sair("nao achei urlpatterns em config/urls.py; acrescente na mao: " + linha)
        linhas.insert(i + 1, "    " + linha)
    backup(caminho)
    caminho.write_text("\n".join(linhas) + "\n", encoding="utf-8")
    print("   rota ficha/ acrescentada")


def acrescentar_botao(arquivo, ancora, novo, depois, descricao):
    caminho = PASTA / "estoque" / "templates" / "estoque" / arquivo
    if not caminho.exists():
        print(f"   AVISO: {caminho.relative_to(PASTA)} nao encontrado. Acrescente na mao: {novo.strip()}")
        return
    texto = caminho.read_text(encoding="utf-8")
    if "ficha_editar" in texto:
        print(f"   {arquivo}: botao ja existe")
        return
    if ancora not in texto:
        print(f"   AVISO: nao achei o ponto de insercao em {arquivo} ({descricao}).")
        print(f"          Acrescente na mao, onde ficam os botoes: {novo.strip()}")
        return
    backup(caminho)
    substituto = ancora + novo if depois else novo + ancora
    caminho.write_text(texto.replace(ancora, substituto, 1), encoding="utf-8")
    print(f"   {arquivo}: botao 'Ficha diaria' acrescentado")


def ajustar_templates_estoque():
    print("4) Botoes 'Ficha diaria' no estoque")
    acrescentar_botao(
        "relatorio_list.html",
        """<a href="{% url 'relatorio_imprimir' r.pk %}" target="_blank">Imprimir</a>""",
        """\n      <a href="{% url 'ficha_editar' r.pk %}">Ficha di\u00e1ria</a>""",
        True, "lista de relatorios")
    acrescentar_botao(
        "relatorio_folha.html",
        """<a class="btn" href="{% url 'relatorio_lista' %}">Voltar</a>""",
        """<a class="btn" href="{% url 'ficha_editar' rel.pk %}">Ficha di\u00e1ria</a>\n    """,
        False, "barra de botoes da folha")


def migrar():
    print("5) Banco de dados")
    for comando in (["makemigrations", APP], ["migrate"]):
        print("   python manage.py", " ".join(comando))
        r = subprocess.run([sys.executable, "manage.py", *comando])
        if r.returncode != 0:
            sair("o comando acima falhou; leia a mensagem e me envie o texto completo.")


def main():
    if not (PASTA / "manage.py").exists() or not (PASTA / "config" / "settings.py").exists():
        sair("rode este script dentro da pasta do projeto (onde esta o manage.py, com a pasta config).")
    if not (PASTA / "estoque").exists():
        sair("a pasta estoque nao foi encontrada; a ficha diaria depende do app estoque.")
    instalar_arquivos()
    ajustar_settings()
    ajustar_urls()
    ajustar_templates_estoque()
    if "--sem-migrar" in sys.argv:
        print("5) migracoes puladas (--sem-migrar)")
    else:
        migrar()
    print()
    print("Pronto! Rode: python manage.py runserver")
    print("Abra um relatorio em /livraria/ e clique em 'Ficha diaria'.")


if __name__ == "__main__":
    main()
